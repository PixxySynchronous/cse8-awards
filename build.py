"""Builds public/ from ../data. Re-run after editing awards.json, cr_messages.json or certificates.

    /opt/anaconda3/bin/python -I build.py          # site files
    /opt/anaconda3/bin/python -I build.py --links  # also print each student's private QR link
"""
import base64, hashlib, hmac, json, os, sys
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
DATA = Path(os.environ.get("DATA_DIR", HERE.parent / "data"))
PUB = HERE / "public"
SITE_URL = os.environ.get("SITE_URL", "https://cse8-awards.vercel.app")

awards = json.loads((DATA / "awards.json").read_text())
msgs = json.loads((DATA / "cr_messages.json").read_text())
hot = json.loads((DATA / "hot_words.json").read_text())


def shrink(src, dst, width):
    if dst.exists() and dst.stat().st_mtime >= src.stat().st_mtime:
        return
    im = Image.open(src).convert("RGB")
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    im.save(dst, "JPEG", quality=82, optimize=True, progressive=True)


(PUB / "bg").mkdir(parents=True, exist_ok=True)
(PUB / "certs").mkdir(exist_ok=True)

students = {}
for a in awards:
    sid = a["id"]
    bg = Path(a["background"]).name
    shrink(DATA / a["background"], PUB / "bg" / bg, 1800)
    shrink(DATA / "certificates" / f"{sid}.jpg", PUB / "certs" / f"{sid}.jpg", 1400)
    first = a["name"].split()[0]
    students[sid] = {
        "name": a["name"],
        "award": a["main_award"],
        "hot": hot.get(sid, []),
        "why": a.get("subtext", ""),
        "others": a["other_awards"],
        "bg": bg,
        "flip": a["background_flipped"],
        "msg": msgs.get(sid) or [f"{first}, your message from the CR is on its way."],
    }

(PUB / "students.json").write_text(json.dumps(students, ensure_ascii=False, separators=(",", ":")))
names = json.dumps({k: v["name"] for k, v in students.items()}, ensure_ascii=False, indent=1)
(HERE / "api" / "_names.js").write_text(f"// generated by build.py: id -> name\nexport const NAMES = {names};\n")
print(f"built {len(students)} students -> {PUB}")

if "--links" in sys.argv:
    secret = (HERE / ".secret").read_text().strip()
    for sid in students:
        k = base64.urlsafe_b64encode(hmac.new(secret.encode(), sid.encode(), hashlib.sha256).digest())[:12].decode()
        print(f"{sid},{SITE_URL}/{sid}?k={k}")
